"use client";

import Link from "next/link";
import { DocsLayout } from "../../../components/docs-layout";
import { PresetsHeader, usePresetGroups } from "../../../components/presets";
import { PresetComparison } from "../../../components/preset-preview";
import {
  BrandDisclaimer,
  PresetCatalogCard,
  usePresetCatalog,
} from "../../../components/preset-catalog";
import { PresetSemanticDiff } from "../../../components/preset-diff";
import { BrandIdentity } from "./brand-identity";

/**
 * `/presets/brand` — brand-inspired starting points.
 *
 * ## What this page is
 *
 * Not the default page with different data. The claim it has to demonstrate is
 * narrower and harder:
 *
 * > Themvora can preserve an *external* identity inside its semantic-token
 * > system, and still hold the contrast contract.
 *
 * The page shows that claim rather than asserting it: the brand's seed beside the
 * resolved tokens, the semantic diff against a neutral default, and a live
 * preview rendered from the generated result.
 *
 * ## Positioning
 *
 * `default` teaches the palette system. `brand` shows what happens when someone
 * else's colour is the input. The two pages therefore open differently and make
 * different arguments.
 */
export function BrandPresetsView() {
  const groups = usePresetGroups("brand");
  const catalog = usePresetCatalog("brand");

  // Graphite is the achromatic default, so a brand compared against it reads as
  // "what the brand changed" rather than "two hues fighting".
  const defaultCatalog = usePresetCatalog("default");
  const baseline = defaultCatalog.find((entry) => entry.id === "graphite") ?? defaultCatalog[0];

  // The default preset's neutral family is the "Changes from Default" baseline
  // for the comparison surface below — same token vocabulary, so the diff is
  // meaningful.
  const defaultGroups = usePresetGroups("default");
  const comparisonBaseline = defaultGroups.find((g) => g.key === "neutral") ?? defaultGroups[0];

  return (
    <DocsLayout>
      <div className="max-w-5xl">
        <PresetsHeader kind="brand" />

        <BrandIdentity />

        <section className="mb-10">
          <h2 className="text-lg font-semibold tracking-tight mb-1">
            What &ldquo;Brand&rdquo; means here
          </h2>
          <p className="text-sm opacity-70 mb-4 leading-relaxed max-w-3xl">
            A brand preset is a <strong>starting point</strong>, not a
            reproduction. The brand&rsquo;s signature colour anchors the identity
            and everything else is generated by Themvora&rsquo;s semantic rules —
            so the result is a complete, contrast-checked light/dark family you can
            actually ship, not a scraped palette that might not be readable.
            Apply one, then override individual tokens in your own theme.
          </p>
          <BrandDisclaimer />
        </section>

        <section className="mb-12">
          <h2 className="text-lg font-semibold tracking-tight mb-1">
            The brand presets
          </h2>
          <p className="text-sm opacity-70 mb-5 leading-relaxed max-w-3xl">
            Five recipes, each anchored to a different brand hue. Open
            &ldquo;Changes from Graphite&rdquo; on a card to see which design
            decisions the brand actually moved — primary identity, surface
            temperature, surface depth — and which ones stayed put. The status
            colours are the clearest case: they are seed-independent by design, so
            every brand shares them.
          </p>

          <div className="grid gap-5 sm:grid-cols-2">
            {catalog.map((entry) => (
              <PresetCatalogCard
                key={entry.id}
                entry={entry}
                footer={<PresetSemanticDiff entry={entry} baseline={baseline} />}
              />
            ))}
          </div>
        </section>

        <section className="mb-10">
          <h2 className="text-lg font-semibold tracking-tight mb-1">
            Compare against Default
          </h2>
          <p className="text-sm opacity-70 mb-4 leading-relaxed max-w-3xl">
            The same interface as the default preset, under a brand palette.
            &ldquo;Show changes from Default&rdquo; isolates exactly which tokens
            differ. This changes only the preview, not the documentation site. The
            snippet below the preview follows your selection.
          </p>
          <PresetComparison
            groups={groups}
            kind="brand"
            {...(comparisonBaseline ? { baseline: comparisonBaseline } : {})}
          />
        </section>

        <section className="mb-10">
          <h2 className="text-lg font-semibold tracking-tight mb-1">
            Use it in your app
          </h2>
          <p className="text-sm opacity-70 mb-4 leading-relaxed max-w-3xl">
            Brand presets ship inside{" "}
            <code className="mono text-[0.9em]">@themvora/core</code> via{" "}
            <code className="mono text-[0.9em]">getBrandPresets()</code> — one
            light/dark family per brand. Pick your framework in the preview above
            and copy the snippet for the brand you were looking at.
          </p>
          <Link
            href="/custom-themes#presets"
            className="inline-flex items-center gap-1.5 text-sm text-primary no-underline font-medium hover:underline"
          >
            Learn how to define your own themes →
          </Link>
        </section>
      </div>
    </DocsLayout>
  );
}
