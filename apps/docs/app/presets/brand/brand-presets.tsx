"use client";

import Link from "next/link";
import { DocsLayout } from "../../../components/docs-layout";
import { PresetsHeader, usePresetGroups } from "../../../components/presets";
import { PresetComparison } from "../../../components/preset-preview";
import type { PresetJavaScript } from "../../../lib/preset-js";
import {
  BrandDisclaimer,
  PresetCatalogCard,
  usePresetCatalog,
} from "../../../components/preset-catalog";
import { BrandIdentity } from "./brand-identity";

/**
 * `/presets/brand` — brand-inspired starting points.
 *
 * Themvora can preserve an external identity inside its semantic-token system
 * while holding the contrast contract. The brand's seed anchors the identity;
 * everything else is generated. Details about reference colors, interpretation
 * and normalization live behind expandable sections so the page stays scannable.
 */
export function BrandPresetsView({
  jsSources,
  labels,
  jsSourcesUnfiltered,
  labelsUnfiltered,
  jsSourcesFamilyPicker,
  labelsFamilyPicker,
}: {
  jsSources?: PresetJavaScript;
  labels?: Record<string, string>;
  jsSourcesUnfiltered?: PresetJavaScript;
  labelsUnfiltered?: Record<string, string>;
  jsSourcesFamilyPicker?: PresetJavaScript;
  labelsFamilyPicker?: Record<string, string>;
}) {
  const groups = usePresetGroups("brand");
  const catalog = usePresetCatalog("brand");

  const defaultGroups = usePresetGroups("default");
  const comparisonBaseline = defaultGroups.find((g) => g.key === "neutral") ?? defaultGroups[0];

  return (
    <DocsLayout wide>
      <div className="max-w-5xl">
        <PresetsHeader kind="brand" />

        <details className="group rounded-xl border border-border bg-card/40 mb-10">
          <summary className="flex items-center gap-2 px-4 py-3 cursor-pointer list-none text-sm font-semibold">
            <span>Brand reference &amp; interpretation</span>
            <span className="opacity-40 transition-transform group-open:rotate-90 ml-auto">›</span>
          </summary>
          <div className="px-4 pb-4 border-t border-border pt-3">
            <BrandIdentity />
          </div>
        </details>

        <section className="mb-10">
          <p className="text-sm opacity-70 mb-4 leading-relaxed max-w-3xl">
            A brand preset is a <strong>starting point</strong>, not a
            reproduction. The brand&rsquo;s signature colour anchors the identity
            and everything else is generated by Themvora&rsquo;s semantic rules —
            so the result is a complete, contrast-checked light/dark family you can
            ship. Apply one, then override individual tokens in your own theme.
          </p>
          <BrandDisclaimer />
        </section>

        <section className="mb-12">
          <h2 className="text-lg font-semibold tracking-tight mb-1">
            The brand presets
          </h2>
          <p className="text-sm opacity-70 mb-5 leading-relaxed max-w-3xl">
            Five recipes, each anchored to a different brand hue. Expand
            &ldquo;Details&rdquo; on any card to see what changed against the
            default baseline.
          </p>

          <div className="grid gap-5 sm:grid-cols-2 lg:grid-cols-3">
            {catalog.map((entry) => (
              <PresetCatalogCard
                key={entry.id}
                entry={entry}
              />
            ))}
          </div>
        </section>

        <section className="mb-10">
          <h2 className="text-lg font-semibold tracking-tight mb-1">
            Compare &amp; use
          </h2>
          <p className="text-sm opacity-70 mb-4 leading-relaxed max-w-3xl">
            Preview a brand palette against the same interface used on the Default
            page. &ldquo;Show changes from Default&rdquo; isolates which tokens
            differ.
          </p>
          <PresetComparison
            groups={groups}
            kind="brand"
            {...(comparisonBaseline ? { baseline: comparisonBaseline } : {})}
            {...(jsSources ? { jsSources } : {})}
            {...(labels ? { labels } : {})}
            {...(jsSourcesUnfiltered ? { jsSourcesUnfiltered } : {})}
            {...(labelsUnfiltered ? { labelsUnfiltered } : {})}
            {...(jsSourcesFamilyPicker ? { jsSourcesFamilyPicker } : {})}
            {...(labelsFamilyPicker ? { labelsFamilyPicker } : {})}
          />
        </section>

        <section className="mb-10">
          <Link
            href="/custom-themes#presets"
            className="inline-flex items-center gap-1.5 text-sm text-primary no-underline font-medium hover:underline"
          >
            Define your own themes →
          </Link>
        </section>
      </div>
    </DocsLayout>
  );
}
