/**
 * `themvora add` — extend an existing project's theme registry.
 *
 * `init` writes a registry; `add` extends the same file. It works the way `init`
 * does, and for the same reason: the registry file records the sources it was
 * built from in a machine-readable header, so `add` decodes that list, appends
 * its own source, resolves everything through the *same* source resolver, and
 * regenerates the file with the *same* renderer.
 *
 * Nothing about a framework lives here. The registry file and its renderer come
 * from `init/registry-file.ts`, so adding a framework remains a registry change.
 *
 * @packageDocumentation
 */
import { resolve } from "node:path";
import { getBool, getString } from "../utils.js";
import type { ParsedArgs } from "../utils.js";
import { CommandExit, ExitCodes, UsageError } from "../exit-codes.js";
import {
  failure,
  paint,
  status,
  wantsJson,
  wantsQuiet,
  writeJson,
} from "../output.js";
import { readProjectFile, planFile } from "../init/files.js";
import { defaultIo, resolveInsideProject } from "../init/apply.js";
import {
  findAnyRegistryFile,
  findRegistryFile,
} from "../init/registry-file.js";
import {
  resolveSources,
  encodeSource,
  readSources,
  type SourceRequest,
} from "../init/source.js";
import type { AddPlan, AddReport } from "../init/types.js";

/** The source kinds `add` accepts. */
const KINDS = ["preset", "brand", "seed"] as const;

type Kind = (typeof KINDS)[number];

/**
 * Read the source to add from the positionals.
 *
 * @param args - The parsed arguments.
 * @returns The source request.
 *
 * @throws {UsageError} When the kind is missing, unknown, or has no value.
 */
function readRequest(args: ParsedArgs): SourceRequest {
  const kind = args._[1];
  const value = args._[2] ?? getString(args, "id");

  if (kind === undefined) {
    throw new UsageError(
      `a source kind is required — use one of: ${KINDS.join(", ")} (e.g. themvora add preset mint)`,
    );
  }
  if (!(KINDS as readonly string[]).includes(kind)) {
    throw new UsageError(
      `unknown source kind "${kind}" — use one of: ${KINDS.join(", ")}`,
    );
  }
  if (value === undefined) {
    throw new UsageError(
      `"add ${kind}" needs a value (e.g. themvora add ${kind} <id>)`,
    );
  }

  const source = kind as Kind;
  if (source === "seed") {
    const family = getString(args, "family");
    const style = getString(args, "style");
    return {
      kind: "seed",
      seed: value,
      ...(family !== undefined ? { family } : {}),
      ...(style !== undefined ? { style } : {}),
    };
  }
  return source === "brand"
    ? { kind: "brand", id: value }
    : { kind: "preset", id: value };
}

/**
 * Build the plan for an `add`.
 *
 * @param target - The project directory.
 * @param request - The source to add.
 * @param force - Whether an existing registry may be replaced.
 * @returns The plan.
 *
 * @throws {UsageError} When the project has no Themvora registry.
 * @throws {Error} When the registry cannot be extended safely.
 */
export function buildAddPlan(
  target: string,
  request: SourceRequest,
  force: boolean,
): AddPlan {
  const projectPath = resolve(target);
  const read = (relativePath: string) =>
    readProjectFile(projectPath, relativePath);

  const found = findRegistryFile(projectPath, read);
  if (!found) {
    const anyFile = findAnyRegistryFile(read);
    throw new UsageError(
      anyFile
        ? `${anyFile} was not generated by Themvora, so \`add\` will not rewrite it — add the themes to it by hand, or remove the file and run \`themvora init\` again`
        : `no Themvora theme registry found in ${projectPath} — run \`themvora init\` first`,
    );
  }

  const { file, contents } = found;
  const existing = readSources(contents);

  if (existing.requests.length === 0 && existing.unknown.length === 0) {
    throw new Error(
      `${file.path} does not record the theme sources it was built from, so \`add\` cannot extend it safely. ` +
        "Re-run `themvora init` in this project to regenerate the registry, then add the source again.",
    );
  }

  if (existing.unknown.length > 0) {
    throw new Error(
      `${file.path} records ${existing.unknown.length} theme source(s) this version of the CLI does not understand — upgrade @themvora/cli, or edit the file by hand`,
    );
  }

  const encoded = encodeSource(request);
  const alreadyPresent = existing.requests.some(
    (candidate) => encodeSource(candidate) === encoded,
  );

  const merged = alreadyPresent
    ? existing.requests
    : [...existing.requests, request];
  const resolved = resolveSources(merged);
  const previous = resolveSources(existing.requests);

  const before = new Set(previous.summary.themes);
  const added = resolved.summary.themes.filter((name) => !before.has(name));

  const warnings: string[] = [];
  if (resolved.problems.length > 0) {
    warnings.push(
      `the resolved registry has ${resolved.problems.length} validation problem(s): ${resolved.problems.join("; ")}`,
    );
  }

  const nextContents = file.render(resolved.themes, resolved.summary);

  return {
    version: 1,
    projectPath,
    registry: file.path,
    framework: file.framework,
    source: { encoded, label: resolved.summary.label },
    sources: resolved.summary.sources,
    themes: resolved.summary.themes,
    added,
    defaultTheme: resolved.summary.defaultTheme,
    file: planFile({
      path: file.path,
      contents: nextContents,
      existing: contents,
      generated: true,
      reason: alreadyPresent ? "already present" : "add the theme source",
      force,
    }),
    warnings,
  };
}

/** Render a plan for a human. */
function renderPlan(plan: AddPlan): string {
  const lines: string[] = [];
  lines.push(paint("bold", "themvora add — plan"));
  lines.push("");
  lines.push(`  project    ${plan.projectPath}`);
  lines.push(`  registry   ${plan.registry}`);
  lines.push(`  source     ${plan.source.label}`);
  lines.push("");

  if (plan.added.length === 0) {
    lines.push("  Already present — nothing to add.");
  } else {
    lines.push(`  Adds ${plan.added.length} theme(s):`);
    for (const name of plan.added)
      lines.push(`    ${paint("green", "+")} ${name}`);
    lines.push("");
    lines.push(
      `  Registry would carry ${plan.themes.length} theme(s), opening on ${plan.defaultTheme}.`,
    );
  }

  if (plan.warnings.length > 0) {
    lines.push("");
    for (const warning of plan.warnings)
      lines.push(`  ${paint("yellow", "!")} ${warning}`);
  }

  return lines.join("\n");
}

/** Render a report for a human. */
function renderReport(report: AddReport): string {
  const lines: string[] = [];
  lines.push(paint("bold", "themvora add — done"));
  lines.push("");
  lines.push(`  project    ${report.projectPath}`);
  lines.push(`  registry   ${report.registry}`);
  lines.push("");

  if (!report.changed) {
    lines.push("  Already present — nothing changed.");
  } else {
    for (const name of report.added)
      lines.push(`    ${paint("green", "+")} ${name}`);
    lines.push("");
    lines.push(`  Registry now carries ${report.themes.length} theme(s).`);
  }

  if (report.nextSteps.length > 0) {
    lines.push("");
    lines.push("  next");
    for (const step of report.nextSteps) lines.push(`    ${step}`);
  }

  return lines.join("\n");
}

/**
 * Run `themvora add`.
 *
 * @param args - The parsed arguments.
 *
 * @throws {UsageError} When the source kind or value is missing or invalid.
 * @throws {CommandExit} With `1` when a hand-maintained registry blocks the run.
 */
export async function cmdAdd(args: ParsedArgs): Promise<void> {
  const request = readRequest(args);
  // `add <kind> <value>` uses both positionals, so the project directory comes
  // from `--dir` (or the current directory).
  const directory = getString(args, "dir") ?? ".";
  const json = wantsJson(args);
  const quiet = wantsQuiet(args);
  const planOnly = getBool(args, "plan");
  const dryRun = getBool(args, "dry-run");
  const force = getBool(args, "force");

  let plan: AddPlan;
  try {
    plan = buildAddPlan(directory, request, force);
  } catch (error) {
    // `UsageError` already carries a usage hint and is reported by the
    // dispatcher. Anything else is a state problem, and `CommandExit` is silent
    // by design, so the message has to be written before throwing.
    if (error instanceof UsageError) throw error;
    const message = error instanceof Error ? error.message : String(error);
    failure(message);
    throw new CommandExit(ExitCodes.Error, message);
  }

  if (planOnly || dryRun) {
    if (json) writeJson(plan);
    else process.stdout.write(`${renderPlan(plan)}\n`);
    return;
  }

  if (plan.file.action === "conflict") {
    const message = `conflict: ${plan.file.path} — ${plan.file.reason}`;
    failure(message);
    throw new CommandExit(ExitCodes.Error, message);
  }

  const changed = plan.file.action !== "unchanged";
  if (changed) {
    defaultIo.writeFile(
      resolveInsideProject(plan.projectPath, plan.file.path),
      plan.file.contents,
    );
    if (!quiet) status(`Updated ${plan.registry}`);
  }

  const report: AddReport = {
    version: 1,
    projectPath: plan.projectPath,
    registry: plan.registry,
    changed,
    themes: plan.themes,
    added: plan.added,
    nextSteps: changed
      ? [
          `The themes are registered in ${plan.registry} — reference them by name.`,
          "Restart the dev server so the new themes are picked up.",
        ]
      : [],
  };

  if (json) writeJson(report);
  else process.stdout.write(`${renderReport(report)}\n`);
}
