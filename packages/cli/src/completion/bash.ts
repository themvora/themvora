/**
 * Bash completion renderer.
 *
 * The script resolves registry values by calling `themvora list <registry>
 * --ids` on first use and caching the result in a shell variable, so a Tab press
 * costs one process at most once per shell session rather than on every press.
 *
 * @packageDocumentation
 */
import { commandSpellings, type CompletionSpec } from "./spec.js";

/** Quote a word list for `compgen -W`. */
function words(values: readonly string[]): string {
  return values.join(" ");
}

/**
 * Render the bash completion script.
 *
 * @param spec - The completion model.
 * @returns The script, ending in a newline.
 */
export function renderBash(spec: CompletionSpec): string {
  const commands = words(commandSpellings(spec));

  // One `case` arm per registry flag, across every command. The flag is what
  // the cursor follows, so the command it belongs to does not matter here.
  const registryArms = spec.commands
    .flatMap((command) =>
      Object.entries(command.registryValues).map(
        ([flag, selector]) => `        ${flag}) _themvora_values ${selector} "$cur"; return 0 ;;`,
      ),
    )
    .join("\n");

  const closedArms = spec.commands
    .flatMap((command) =>
      Object.entries(command.closedValues).map(
        ([flag, values]) => `        ${flag}) COMPREPLY=( $(compgen -W "${words(values)}" -- "$cur") ); return 0 ;;`,
      ),
    )
    .join("\n");

  const flagCases = spec.commands
    .map(
      (command) =>
        `        ${[command.name, ...command.aliases].join("|")})\n` +
        `            COMPREPLY=( $(compgen -W "${words([...command.flags, ...spec.globalFlags])}" -- "$cur") )\n` +
        `            return 0\n` +
        `            ;;`,
    )
    .join("\n");

  const positionalCases = spec.commands
    .filter((command) => Object.keys(command.positionalValues).length > 0)
    .map((command) => {
      const values = Object.values(command.positionalValues)[0]!;
      return `        ${[command.name, ...command.aliases].join("|")})\n` +
        `            COMPREPLY=( $(compgen -W "${words(values)}" -- "$cur") )\n` +
        `            return 0\n` +
        `            ;;`;
    })
    .join("\n");

  return `# bash completion for ${spec.program}
# Generated by \`${spec.program} completion bash\`. Do not edit by hand.
#
# Registry values (presets, brands, styles, frameworks) are read from the
# installed CLI at completion time, so they cannot go stale.

_themvora_values() {
    # Two local statements, not one. Bash marks every name in a single local
    # declaration as local *before* assigning any of them, so combining
    # "local selector=\\"$1\\" cache=\\"x_$selector\\"" would build the cache name
    # from an empty selector — every registry would then share one cache key and
    # the first one fetched would answer for all of them.
    local selector="$1"
    local cur="$2"
    local cache="_themvora_ids_$selector"
    if [[ -z "\${!cache}" ]]; then
        printf -v "$cache" '%s' "$(${spec.program} list "$selector" --ids 2>/dev/null)"
    fi
    COMPREPLY=( $(compgen -W "\${!cache}" -- "$cur") )
}

_themvora_complete() {
    local cur prev cmd i
    COMPREPLY=()
    cur="\${COMP_WORDS[COMP_CWORD]}"
    prev="\${COMP_WORDS[COMP_CWORD-1]}"

    # The subcommand is the first word that is not an option.
    cmd=""
    for ((i = 1; i < COMP_CWORD; i++)); do
        case "\${COMP_WORDS[i]}" in
            -*) continue ;;
            *) cmd="\${COMP_WORDS[i]}"; break ;;
        esac
    done

    if [[ -z "$cmd" ]]; then
        COMPREPLY=( $(compgen -W "${commands}" -- "$cur") )
        return 0
    fi

    # A value position is decided by the *previous* word.
    case "$prev" in
${registryArms}
${closedArms}
    esac

    if [[ "$cur" == -* ]]; then
        case "$cmd" in
${flagCases}
        esac
        return 0
    fi

    case "$cmd" in
${positionalCases}
    esac

    COMPREPLY=( $(compgen -f -- "$cur") )
    return 0
}

complete -o default -F _themvora_complete ${spec.program}
`;
}
