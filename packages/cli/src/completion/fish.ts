/**
 * Fish completion renderer.
 *
 * Fish's declarative model is the cleanest of the four: a registry-backed
 * argument is just `-a "(themvora list presets --ids)"`, so the values are
 * resolved by fish itself at completion time with no caching code.
 *
 * @packageDocumentation
 */
import { commandSpellings, type CompletionSpec } from "./spec.js";

/** Escape a string for a double-quoted fish argument. */
function quote(value: string): string {
  return `"${value.replace(/(["\\$])/g, "\\$1")}"`;
}

/**
 * Render the fish completion script.
 *
 * @param spec - The completion model.
 * @returns The script, ending in a newline.
 */
export function renderFish(spec: CompletionSpec): string {
  const lines: string[] = [
    `# fish completion for ${spec.program}`,
    `# Generated by \`${spec.program} completion fish\`. Do not edit by hand.`,
    "#",
    "# Registry values (presets, brands, styles, frameworks) are read from the",
    "# installed CLI at completion time, so they cannot go stale.",
    "",
    `function __themvora_no_subcommand`,
    `    for i in (commandline -opc)`,
    `        if contains -- $i ${commandSpellings(spec).join(" ")}`,
    `            return 1`,
    `        end`,
    `    end`,
    `    return 0`,
    `end`,
    "",
    `function __themvora_using`,
    `    set -l cmd (commandline -opc)`,
    `    if test (count $cmd) -lt 2`,
    `        return 1`,
    `    end`,
    `    contains -- $cmd[2] $argv`,
    `end`,
    "",
  ];

  // The subcommand list.
  for (const command of spec.commands) {
    lines.push(
      `complete -c ${spec.program} -n __themvora_no_subcommand -a ${quote(command.name)} -d ${quote(command.summary)}`,
    );
  }
  lines.push("");

  // Per command: flags, registry-backed values and closed value sets.
  for (const command of spec.commands) {
    const condition = `__themvora_using ${[command.name, ...command.aliases].join(" ")}`;

    for (const flag of [...command.flags, ...spec.globalFlags]) {
      const registry = command.registryValues[flag];
      if (registry) {
        lines.push(
          `complete -c ${spec.program} -n ${quote(condition)} -l ${flag.replace(/^--/, "")} -a "(${spec.program} list ${registry} --ids)"`,
        );
        continue;
      }
      const closed = command.closedValues[flag];
      if (closed) {
        lines.push(
          `complete -c ${spec.program} -n ${quote(condition)} -l ${flag.replace(/^--/, "")} -a ${quote(closed.join(" "))}`,
        );
        continue;
      }
      lines.push(`complete -c ${spec.program} -n ${quote(condition)} -l ${flag.replace(/^--/, "")}`);
    }

    for (const flag of command.shortFlags) {
      lines.push(
        `complete -c ${spec.program} -n ${quote(condition)} -s ${flag.replace(/^-/, "")}`,
      );
    }

    // A positional that is a closed set.
    for (const values of Object.values(command.positionalValues)) {
      lines.push(
        `complete -c ${spec.program} -n ${quote(condition)} -f -a ${quote(values.join(" "))}`,
      );
    }
    lines.push("");
  }

  return `${lines.join("\n").replace(/\n+$/, "")}\n`;
}
