/**
 * PowerShell completion renderer.
 *
 * `Register-ArgumentCompleter` with a script block. Registry values are fetched
 * by invoking the CLI at completion time and caching the result in a script-scope
 * variable, so a Tab press does not spawn a process every time.
 *
 * @packageDocumentation
 */
import { commandSpellings, type CompletionSpec } from "./spec.js";

/** Escape a string for a single-quoted PowerShell literal. */
function single(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

/** A PowerShell array literal of single-quoted strings. */
function array(values: readonly string[]): string {
  return `@(${values.map(single).join(", ")})`;
}

/** A PowerShell hashtable literal from a record of string arrays. */
function hashtable(record: Readonly<Record<string, readonly string[]>>): string {
  const entries = Object.entries(record).map(
    ([key, values]) => `        ${single(key)} = ${array(values)}`,
  );
  return entries.length === 0 ? "@{}" : `@{\n${entries.join("\n")}\n    }`;
}

/** A PowerShell hashtable literal from a record of strings. */
function stringMap(record: Readonly<Record<string, string>>): string {
  const entries = Object.entries(record).map(
    ([key, value]) => `        ${single(key)} = ${single(value)}`,
  );
  return entries.length === 0 ? "@{}" : `@{\n${entries.join("\n")}\n    }`;
}

/**
 * Render the PowerShell completion script.
 *
 * @param spec - The completion model.
 * @returns The script, ending in a newline.
 */
export function renderPowerShell(spec: CompletionSpec): string {
  const perCommand = spec.commands
    .map((command) => {
      const names = [command.name, ...command.aliases].map(single).join(", ");
      return `    ${single(command.name)} = @{
        Names      = @(${names})
        Flags      = ${array([...command.flags, ...command.shortFlags, ...spec.globalFlags])}
        Registry   = ${stringMap(command.registryValues)}
        Closed     = ${hashtable(command.closedValues)}
        Positional = ${hashtable(
          Object.fromEntries(
            Object.entries(command.positionalValues).map(([index, values]) => [index, values]),
          ),
        )}
    }`;
    })
    .join("\n");

  return `# PowerShell completion for ${spec.program}
# Generated by \`${spec.program} completion powershell\`. Do not edit by hand.
#
# Registry values (presets, brands, styles, frameworks) are read from the
# installed CLI at completion time, so they cannot go stale.

$script:ThemvoraCommands = @(
${commandSpellings(spec).map((name) => `    ${single(name)}`).join("\n")}
)

$script:ThemvoraSpec = @{
${perCommand}
}

$script:ThemvoraRegistryCache = @{}

function Get-ThemvoraRegistryValues {
    param([string] $Selector)
    if (-not $script:ThemvoraRegistryCache.ContainsKey($Selector)) {
        $values = & ${spec.program} list $Selector --ids 2>$null
        $script:ThemvoraRegistryCache[$Selector] = @($values)
    }
    return $script:ThemvoraRegistryCache[$Selector]
}

Register-ArgumentCompleter -Native -CommandName ${spec.program} -ScriptBlock {
    param($wordToComplete, $commandAst, $cursorPosition)

    $elements = $commandAst.CommandElements | ForEach-Object { $_.ToString() }
    $previous = if ($elements.Count -ge 2) { $elements[-1] } else { '' }
    if ($wordToComplete -ne '' -and $elements.Count -ge 2) {
        $previous = $elements[-2]
    }

    # The subcommand is the first element that is not an option.
    $command = $null
    foreach ($element in $elements[1..($elements.Count - 1)]) {
        if ($element -notlike '-*') { $command = $element; break }
    }

    $suggestions = @()

    if (-not $command) {
        $suggestions = $script:ThemvoraCommands
    }
    else {
        $spec = $script:ThemvoraSpec[$command]
        if ($spec) {
            if ($spec.Registry.ContainsKey($previous)) {
                $suggestions = Get-ThemvoraRegistryValues $spec.Registry[$previous]
            }
            elseif ($spec.Closed.ContainsKey($previous)) {
                $suggestions = $spec.Closed[$previous]
            }
            elseif ($wordToComplete -like '-*') {
                $suggestions = $spec.Flags
            }
            else {
                foreach ($values in $spec.Positional.Values) { $suggestions += $values }
            }
        }
    }

    $suggestions |
        Where-Object { $_ -like "$wordToComplete*" } |
        ForEach-Object {
            [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterValue', $_)
        }
}
`;
}
