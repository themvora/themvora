/**
 * Zsh completion renderer.
 *
 * Emits both the `#compdef` header (for users who drop the file on `$fpath`)
 * and a trailing `compdef` call (for users who `source` it), because both are
 * common and only supporting one of them produces a silently inert script.
 *
 * @packageDocumentation
 */
import { commandSpellings, type CompletionSpec } from "./spec.js";

/** Escape a string for a single-quoted zsh word. */
function single(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

/** Render `'flag:description'` pairs for `_describe`. */
function described(values: readonly string[]): string {
  return values.map((value) => single(value)).join(" ");
}

/**
 * Render the zsh completion script.
 *
 * @param spec - The completion model.
 * @returns The script, ending in a newline.
 */
export function renderZsh(spec: CompletionSpec): string {
  const commandLines = spec.commands
    .map((command) => `        ${single(`${command.name}:${command.summary}`)}`)
    .join("\n");

  const registryArms = spec.commands
    .flatMap((command) =>
      Object.entries(command.registryValues).map(
        ([flag, selector]) => `        ${flag}) _themvora_registry ${selector}; return ;;`,
      ),
    )
    .join("\n");

  const closedArms = spec.commands
    .flatMap((command) =>
      Object.entries(command.closedValues).map(
        ([flag, values]) => `        ${flag}) compadd ${values.join(" ")}; return ;;`,
      ),
    )
    .join("\n");

  const flagCases = spec.commands
    .map((command) => {
      const all = [...command.flags, ...command.shortFlags, ...spec.globalFlags];
      return `        ${[command.name, ...command.aliases].join("|")}) _values 'option' ${described(all)} ;;`;
    })
    .join("\n");

  const positionalCases = spec.commands
    .filter((command) => Object.keys(command.positionalValues).length > 0)
    .map((command) => {
      const values = Object.values(command.positionalValues)[0]!;
      return `        ${[command.name, ...command.aliases].join("|")}) compadd ${values.join(" ")}; return ;;`;
    })
    .join("\n");

  return `#compdef ${spec.program}
# zsh completion for ${spec.program}
# Generated by \`${spec.program} completion zsh\`. Do not edit by hand.
#
# Registry values (presets, brands, styles, frameworks) are read from the
# installed CLI at completion time, so they cannot go stale.

_themvora_registry() {
    local selector="$1"
    typeset -gA _themvora_cache
    if [[ -z "\${_themvora_cache[$selector]}" ]]; then
        _themvora_cache[$selector]="$(${spec.program} list "$selector" --ids 2>/dev/null)"
    fi
    compadd \${(f)_themvora_cache[$selector]}
}

_themvora() {
    local cur prev cmd
    cur="\${words[CURRENT]}"
    prev="\${words[CURRENT-1]}"

    if (( CURRENT == 2 )); then
        local -a commands
        commands=(
${commandLines}
        )
        _describe 'command' commands
        return
    fi

    cmd="\${words[2]}"

    case "$prev" in
${registryArms}
${closedArms}
    esac

    if [[ "$cur" == -* ]]; then
        case "$cmd" in
${flagCases}
        esac
        return
    fi

    case "$cmd" in
${positionalCases}
    esac

    _files
}

compdef _themvora ${spec.program}
`;
}
