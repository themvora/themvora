/**
 * Locating and rewriting a project's generated theme registry.
 *
 * `init` writes the registry; `add` extends it. Both go through this module so
 * there is exactly one description of where the file lives and what it looks
 * like — and, crucially, so `add` never has to *parse* the TypeScript `init`
 * emitted. It reads the machine-readable source line out of the header instead,
 * which is stable under reformatting in a way that the code below it is not.
 *
 * @packageDocumentation
 */
import { renderThemesModule } from "./adapters/themes-module.js";
import { isGenerated } from "./files.js";
import type { ThemeDefinition } from "@themvora/core";
import type { InitSourceSummary } from "./types.js";

/** A generated registry file, and how to write it back. */
export interface RegistryFile {
  /** Path relative to the project root. */
  path: string;
  /** The framework the file belongs to, for messages. */
  framework: "vite" | "next";
  /** Render the file's contents from a merged source. */
  render: (themes: readonly ThemeDefinition[], source: InitSourceSummary) => string;
}

/**
 * The registry files `init` writes, in the order they are looked for.
 *
 * One module name in every framework, in the directory the framework's layout
 * puts it: `src/themes/` for the Vite targets, `themes/` beside `app/` for Next.
 * The renderer takes the merged source, so `add` extends the registry by adding
 * to the source list the module records — which is also what makes the new
 * family appear in `selection` rather than being filtered back out.
 */
export const REGISTRY_FILES: readonly RegistryFile[] = [
  {
    path: "src/themes/themes.ts",
    framework: "vite",
    render: (themes, source) => renderThemesModule(themes, source),
  },
  {
    path: "themes/themes.ts",
    framework: "next",
    render: (themes, source) => renderThemesModule(themes, source),
  },
];

/**
 * Find the project's generated theme registry.
 *
 * @param projectPath - The project root.
 * @param read - A reader for project-relative paths.
 * @returns The registry file and its current contents, or `null`.
 *
 * @remarks
 * A file that exists but is not Themvora-generated is **not** returned. `add`
 * must not rewrite a registry the user maintains by hand, and reporting "no
 * registry" is the honest outcome there — the error message distinguishes the
 * two cases.
 */
export function findRegistryFile(
  projectPath: string,
  read: (relativePath: string) => string | null,
): { file: RegistryFile; contents: string } | null {
  for (const file of REGISTRY_FILES) {
    const contents = read(file.path);
    if (contents !== null && isGenerated(contents)) return { file, contents };
  }
  return null;
}

/**
 * Whether a registry file exists at all, generated by Themvora or not.
 *
 * @param read - A reader for project-relative paths.
 * @returns The path of the first registry file found, or `null`.
 */
export function findAnyRegistryFile(
  read: (relativePath: string) => string | null,
): string | null {
  return REGISTRY_FILES.find((file) => read(file.path) !== null)?.path ?? null;
}
