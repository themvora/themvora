/**
 * Canonical registry access.
 *
 * Every brand, preset and style the CLI exposes is read from `@themvora/core`.
 * Nothing in this package re-lists them: adding a recipe to the core registry
 * makes its identifier discoverable here with no CLI change, which is the
 * property the "no duplicated registry data" gate is actually checking.
 *
 * The read surface is `getPresetCatalog()`. It is the *derived* catalog the
 * preset docs pages and the quality gate already consume, so a preset the CLI
 * generates is byte-for-byte the preset the docs show — the CLI cannot drift
 * from the shipped recipe, because it never builds one of its own.
 *
 * @packageDocumentation
 */
import {
  GENERATION_STYLE_NAMES,
  getPresetCatalog,
  type BrandProvenance,
  type GenerationStyle,
  type PresetCatalogEntry,
  type ThemeDefinition,
} from "@themvora/core";

/** Which canonical registry an entry came from. */
export type RegistryKind = "preset" | "brand";

/** A registry entry as the CLI needs it — no resolved themes, no quality model. */
export interface RegistryEntry {
  /** Stable identifier, e.g. `"mint"`. */
  id: string;
  /** Display name, e.g. `"Mint"`. */
  name: string;
  /** Theme family, e.g. `"mint"`. */
  family: string;
  /** Which registry it belongs to. */
  kind: RegistryKind;
  /** The seed the palette is generated from. */
  seed: string;
  /** The generation style the recipe pins. */
  style: GenerationStyle;
  /** The recipe's one-line character descriptor. */
  description: string;
  /** Free-form recipe tags. */
  tags: readonly string[];
  /**
   * Additional accepted identifiers.
   *
   * Always empty today — the core recipe metadata has no alias field, and
   * inventing per-brand shorthand flags in the CLI is exactly the duplication
   * this module exists to prevent. The lookup is written generically so that
   * adding an alias to the canonical metadata is all it takes to make one work.
   */
  aliases: readonly string[];
  /** How faithful a brand recipe is. Brand entries only. */
  provenance?: BrandProvenance;
  /** The official brand colour, for documentation. Brand entries only. */
  brandColor?: string;
}

/** Memoized catalog — the recipes are cheap (~17 ms) but stable per process. */
let catalog: PresetCatalogEntry[] | null = null;

function entries(): PresetCatalogEntry[] {
  if (catalog === null) catalog = getPresetCatalog();
  return catalog;
}

function toRegistryEntry(entry: PresetCatalogEntry): RegistryEntry {
  const result: RegistryEntry = {
    id: entry.id,
    name: entry.name,
    family: entry.family,
    kind: entry.kind === "brand" ? "brand" : "preset",
    seed: entry.seed,
    style: entry.style,
    description: entry.character,
    tags: entry.tags,
    aliases: [],
  };

  // `exactOptionalPropertyTypes` — omit rather than assign `undefined`.
  if (entry.provenance !== undefined) result.provenance = entry.provenance;
  if (entry.brandColor !== undefined) result.brandColor = entry.brandColor;

  return result;
}

/** Every preset recipe, in gallery order. */
export function listPresets(): RegistryEntry[] {
  return entries()
    .filter((entry) => entry.kind === "default")
    .map(toRegistryEntry);
}

/** Every brand-inspired recipe, in gallery order. */
export function listBrands(): RegistryEntry[] {
  return entries()
    .filter((entry) => entry.kind === "brand")
    .map(toRegistryEntry);
}

/** Every generation style name, from the canonical generation registry. */
export function listStyles(): readonly GenerationStyle[] {
  return GENERATION_STYLE_NAMES;
}

/** The registry for a kind. */
export function listByKind(kind: RegistryKind): RegistryEntry[] {
  return kind === "brand" ? listBrands() : listPresets();
}

/**
 * Look up a registry entry by id or alias.
 *
 * @param kind - Which registry to search.
 * @param id - The identifier the user typed.
 * @returns The entry, or `undefined` when nothing matches.
 */
export function findEntry(kind: RegistryKind, id: string): RegistryEntry | undefined {
  const needle = id.trim().toLowerCase();
  return listByKind(kind).find(
    (entry) =>
      entry.id.toLowerCase() === needle ||
      entry.aliases.some((alias) => alias.toLowerCase() === needle),
  );
}

/**
 * The resolved, contrast-solved themes for a registry entry.
 *
 * These come straight from the canonical catalog, so a preset generated by the
 * CLI is the same object the docs page renders.
 *
 * @param kind - Which registry the id belongs to.
 * @param id - The identifier the user typed.
 * @returns `{ light, dark }`, or `undefined` when the id is unknown.
 */
export function resolveEntryThemes(
  kind: RegistryKind,
  id: string,
): { entry: RegistryEntry; light: ThemeDefinition; dark: ThemeDefinition } | undefined {
  const found = findEntry(kind, id);
  if (!found) return undefined;

  const entry = entries().find((candidate) => candidate.id === found.id);
  if (!entry) return undefined;

  return { entry: found, light: entry.themes.light, dark: entry.themes.dark };
}

/**
 * The full canonical catalog entry for a registry id.
 *
 * Exposes the derived data a registry entry alone does not carry — the quality
 * model, the recipe's character and temperature, and (for brand recipes) the
 * pinned anchors and the normalization the solver applied. `explain` reads this;
 * nothing is re-derived.
 *
 * @param kind - Which registry the id belongs to.
 * @param id - The identifier the user typed.
 * @returns The catalog entry, or `undefined` when the id is unknown.
 */
export function findCatalogEntry(
  kind: RegistryKind,
  id: string,
): PresetCatalogEntry | undefined {
  const found = findEntry(kind, id);
  if (!found) return undefined;
  return entries().find((candidate) => candidate.id === found.id);
}
