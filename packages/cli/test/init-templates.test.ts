/**
 * The generated showcase's shape and the `--styling` choice.
 *
 * These assertions are about the *contract* of a generated project rather than
 * about a particular framework's syntax:
 *
 * - one provider boundary, in the framework's documented place;
 * - the showcase in its own component, not inline in the application root;
 * - a predictable light start;
 * - semantic tokens only, in either styling engine;
 * - a stacked card that is still a card;
 * - a fresh scaffold's unused demo files removed, and an existing project's
 *   files untouched.
 */
