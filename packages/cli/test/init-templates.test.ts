describe("showcase structure", () => {
  it("puts the showcase in its own component for every framework", () => {
    for (const [id, adapter] of Object.entries(ADAPTERS)) {
      const files = adapter.integrate(scaffoldContext()).files;
      const paths = SHOWCASE[id as keyof typeof SHOWCASE];

      const page = fileAt(files, paths.page);
      const switcher = fileAt(files, paths.switcher);

      expect(page, `${id} should generate ${paths.page}`).toBeDefined();
      expect(switcher, `${id} should generate ${paths.switcher}`).toBeDefined();
      expect(page!.contents, `${id} showcase should be generated`).toContain(
        "Generated by `themvora init`.",
      );
    }
  });

  it("keeps the application root free of showcase markup", () => {
    for (const [id, adapter] of Object.entries(ADAPTERS)) {
      const files = adapter.integrate(scaffoldContext()).files;
      const { composes } = COMPOSITION[id as keyof typeof COMPOSITION];
      const root = fileAt(files, composes);

      expect(root, `${id} should generate ${composes}`).toBeDefined();
      // It composes the showcase; it does not contain the design.
      expect(root!.contents, `${id} should render the showcase`).toMatch(/ThemvoraDefault/);
      expect(root!.contents, `${id} should not inline the showcase copy`).not.toContain(
        "Welcome to Themvora",
      );
    }
  });

  it("leaves Next's layout as the document shell", () => {
    const files = nextAdapter.integrate(scaffoldContext()).files;
    const layout = fileAt(files, "app/layout.tsx")!.contents;
    // The generated file *explains* that the provider renders `<html>`/`<body>`,
    // so the assertion is about code, not prose.
    const code = layout.replace(/\/\*\*[\s\S]*?\*\//g, "");

    expect(code).toContain("{children}");
    expect(code).not.toMatch(/<html[\s>]/);
    expect(code).not.toMatch(/<body[\s>]/);
  });
});

describe("the provider boundary", () => {
  it("mounts exactly one provider, in the framework's documented place", () => {
    for (const [id, adapter] of Object.entries(ADAPTERS)) {
      const files = adapter.integrate(scaffoldContext()).files;
      const sites = files.filter((file) => /<ThemeProvider[\s>]/.test(file.contents));

      expect(
        sites.map((file) => file.path),
        `${id} should have exactly one provider site`,
      ).toEqual([COMPOSITION[id as keyof typeof COMPOSITION].provider]);
    }
  });

  it("uses ThemeProvider in main.tsx for React, not createThemeRoot", () => {
    // The provider is flash-free on its own — it paints `<html>` before the first
    // frame — so a client-rendered app needs no bootstrap helper. `createThemeRoot`
    // exists for server rendering, and is not what a generated Vite app uses.
    const files = reactAdapter.integrate(scaffoldContext()).files;
    const main = fileAt(files, "src/main.tsx")!.contents;

    expect(main).toContain('import { ThemeProvider } from "@themvora/react"');
    expect(main).toContain("createRoot(");
    expect(main).toContain("<ThemeProvider");
    expect(main).toContain('initialMode="light"');
    expect(main).not.toContain("createThemeRoot(");

    // And `App` composes rather than providing.
    expect(fileAt(files, "src/App.tsx")!.contents).not.toContain("ThemeProvider");
  });

  it("registers no Themvora Vite plugin", () => {
    for (const id of ["react", "vue", "svelte", "solid"]) {
      const files = ADAPTERS[id as keyof typeof ADAPTERS].integrate(scaffoldContext()).files;
      const config = fileAt(files, "vite.config.ts");

      expect(config, `${id} should generate a Vite config`).toBeDefined();
      expect(config!.contents, `${id} should not register a Themvora plugin`).not.toContain(
        "themvora",
      );
    }
  });
});

describe("the theme module", () => {
  it("defines the custom pair and composes the canonical presets", () => {
    for (const [id, adapter] of Object.entries(ADAPTERS)) {
      const files = adapter.integrate(scaffoldContext()).files;
      const themes = fileAt(files, SHOWCASE[id as keyof typeof SHOWCASE].themes)!.contents;

      expect(themes, `${id} should import the public API`).toContain(
        'import { defineTheme, getPresetThemes } from "@themvora/core"',
      );
      // The blueprint's custom pair, by name and by colour.
      expect(themes).toContain("themvora-default-light");
      expect(themes).toContain("themvora-default-dark");
      expect(themes).toContain("#635BFF");
      expect(themes).toContain("#0A0B14");
      // Preset colours are consumed from the catalog, never re-declared.
      expect(themes).toContain("getPresetThemes()");
      expect(themes).toContain("export const selection = [");
      for (const family of ["themvora", "citrus", "cocoa", "berry"]) {
        expect(themes, `${id} should offer the ${family} family`).toContain(`"${family}"`);
      }
    }
  });

  it("omits the invalid shadow token the blueprint snippet carried", () => {
    // `shadows.sm: "#17172B"` is a bare colour where the schema wants a CSS
    // box-shadow value, so it would emit an unusable `--theme-shadow-sm`.
    const themes = fileAt(
      reactAdapter.integrate(scaffoldContext()).files,
      SHOWCASE.react.themes,
    )!.contents;

    expect(themes).not.toMatch(/shadows/);
  });
});

describe("semantic tokens only", () => {
  it("declares no palette in the plain stylesheet", () => {
    const styles = renderShowcaseCss();

    // No literal colour of any notation, and no second dark-mode mechanism. The
    // only `rgb()` values are neutral alpha shadow fallbacks, which a shadow
    // needs; nothing else is allowed to name a colour.
    expect(styles).not.toMatch(/#[0-9a-fA-F]{3,8}\b/);
    expect(styles).not.toMatch(/\bhsla?\(/);
    expect([...styles.matchAll(/rgba?\([^)]*\)/g)].map((m) => m[0])).toEqual(
      expect.arrayContaining([]),
    );
    for (const match of styles.matchAll(/rgba?\(([^)]*)\)/g)) {
      expect(match[1], "only neutral alpha shadows may use a literal colour").toMatch(/^0 0 0 \//);
    }
    expect(styles).not.toContain("prefers-color-scheme");
    expect(styles).not.toContain("color-scheme");

    // Everything coloured reads a Themvora role.
    expect(styles).toContain("var(--theme-color-background)");
    expect(styles).toContain("var(--theme-color-card)");
    expect(styles).toContain("var(--theme-color-border)");
    expect(styles).toContain("var(--theme-color-primary)");
    expect(styles).toContain("var(--theme-color-ring)");
  });

  it("declares no palette in the Tailwind entry either", () => {
    const styles = renderShowcaseTailwind();

    expect(styles).not.toMatch(/#[0-9a-fA-F]{3,8}\b/);
    expect(styles).not.toContain("prefers-color-scheme");
    expect(styles).toContain('@import "tailwindcss"');
    expect(styles).toContain('@import "@themvora/tailwind"');
  });

  it("themes the document itself in both variants", () => {
    // The utilities on the showcase's own elements paint the cards and the
    // buttons, but nothing paints the page. Without a themed body a dark theme
    // renders dark components on a browser-default white page — verified in a
    // browser, which is the only place it is visible.
    //
    // Both engines use the same document rule: plain `var(--theme-color-*)` reads
    // rather than `@apply`, because a theme applied through the runtime's own
    // variables is correct whether or not Tailwind has processed the sheet yet.
    for (const [engine, styles] of [
      ["css", renderShowcaseCss()],
      ["tailwind", renderShowcaseTailwind()],
    ] as const) {
      expect(styles, `${engine} must theme the page background`).toContain(
        "background: var(--theme-color-background)",
      );
      expect(styles, `${engine} must theme the page text`).toContain(
        "color: var(--theme-color-foreground)",
      );
    }
  });

  it("keeps no component-class stylesheet in the Tailwind variant", () => {
    // The acceptance test: a Tailwind project must not still depend on the
    // plain-CSS variant's component classes.
    const tailwind = renderShowcaseTailwind();

    for (const cls of [".page", ".card", ".button", ".muted", ".badge", ".navbar", ".field"]) {
      expect(tailwind, `${cls} must not be defined in the Tailwind entry`).not.toContain(cls);
    }

    // And the markup uses utilities, not those class names.
    const page = fileAt(
      reactAdapter.integrate(scaffoldContext({}, { styling: "tailwind" })).files,
      SHOWCASE.react.page,
    )!.contents;

    expect(page).toContain("bg-card");
    expect(page).not.toMatch(/className="(page|card|button|muted)"/);
  });

  it("uses no literal colour in any generated component", () => {
    // The theme module is *supposed* to name colours — it is the theme — so it
    // is excluded; everything else reads a token.
    for (const [id, adapter] of Object.entries(ADAPTERS)) {
      const themesPath = SHOWCASE[id as keyof typeof SHOWCASE].themes;

      for (const file of adapter.integrate(scaffoldContext()).files) {
        if (file.action === "delete" || file.path === themesPath) continue;
        if (file.path.endsWith(".css")) continue;
        expect(file.contents, `${id}:${file.path} must not hard-code a colour`).not.toMatch(
          /#[0-9a-fA-F]{3,8}\b/,
        );
      }
    }
  });
});

describe("a stacked card is still a card", () => {
  // The reported defect: the controls card rendered with no background, border,
  // radius, padding or shadow, because `Card` chose `card-stack` *instead of*
  // `card`. `card-stack` is an additive rhythm modifier in both engines.
  it("composes card and card-stack in every framework and both engines", () => {
    for (const styling of ["css", "tailwind"] as const) {
      const classes = showcaseClasses(styling);
      expect(classes.cardStack, `${styling}: card-stack must be additive`).not.toBe("");
      expect(classes.card).not.toBe("");

      for (const [id, adapter] of Object.entries(ADAPTERS)) {
        const page = fileAt(
          adapter.integrate(scaffoldContext({}, { styling })).files,
          SHOWCASE[id as keyof typeof SHOWCASE].page,
        )!.contents;

        // Either the helper composes them, or the markup spells both out.
        const composes =
          page.includes(`\${c.card} \${c.cardStack}`) ||
          page.includes(`${classes.card} ${classes.cardStack}`);

        expect(composes, `${id}/${styling} must render card + card-stack together`).toBe(true);
        expect(
          page,
          `${id}/${styling} must never render card-stack alone`,
        ).not.toMatch(/className=\{stack \? "[a-z-]*card-stack/);
      }
    }
  });

  it("keeps the card surface out of the stack modifier", () => {
    // `card-stack` adds the rhythm; the surface belongs to `card`. If the
    // modifier carried the surface, a stack-only card would still look right and
    // the bug would be invisible again.
    const styles = renderShowcaseCss();
    const cardStack = styles.slice(styles.indexOf(".card-stack"));
    const rule = cardStack.slice(0, cardStack.indexOf("}"));

    expect(rule).toContain("display: grid");
    expect(rule).not.toContain("background");
    expect(rule).not.toContain("border");
    expect(rule).not.toContain("padding");
    expect(rule).not.toContain("box-shadow");
  });
});

