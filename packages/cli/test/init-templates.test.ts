/** A context for a project `init` scaffolded, with the given files present. */
function scaffoldContext(
  files: Record<string, string> = {},
  overrides: Partial<{ styling: "css" | "tailwind"; projectKind: "missing" | "existing" }> = {},
) {
  return {
    projectPath: "/tmp/unused",
    projectName: "my-app",
    projectKind: (overrides.projectKind ?? "missing") as "missing" | "existing",
    styling: (overrides.styling ?? "css") as "css" | "tailwind",
    example: false,
    force: false,
    source: SOURCE,
    themes: [],
    imports: IMPORTS,
    read: (path: string) => files[path] ?? null,
    exists: (path: string) => files[path] !== undefined,
    listProjectFiles: () => Object.keys(files),
  };
}

