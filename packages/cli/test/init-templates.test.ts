describe("the scoped-theme identifier comes from the registry", () => {
  // `ThemeScope` accepts a *family name*, so an identifier the catalog does not
  // ship fails silently: the tile just renders unstyled. The module therefore
  // declares the family once and resolves the concrete themes by filtering the
  // registry with that declaration — a demo cannot point at a family nothing
  // offers, and a drift is a compile error rather than an unstyled box.
  const themesOf = (id: keyof typeof ADAPTERS) =>
    fileAt(ADAPTERS[id].integrate(scaffoldContext()).files, SHOWCASE[id].themes)!.contents;

  it("declares the scoped family once and filters the registry by it", () => {
    const themes = themesOf("react");

    const declaration = /^export const scopedFamily = "([a-z-]+)";$/m.exec(themes);
    expect(declaration, "the scoped family must be a single declaration").not.toBeNull();

    // Declared exactly once — a second literal at a use site is the drift.
    expect(themes.match(/export const scopedFamily = /g)).toHaveLength(1);

    // And the resolution filters by the variable, never by a repeated value.
    expect(themes).toContain("theme.meta?.family === scopedFamily");
  });

  it("points the scope at a family the registry actually offers", () => {
    // `selection` is what `presetThemes` is filtered by, so a family outside it
    // resolves to an empty pair and the scoped tile has nothing to render.
    for (const id of Object.keys(ADAPTERS) as (keyof typeof ADAPTERS)[]) {
      const themes = themesOf(id);
      const family = /^export const scopedFamily = "([a-z-]+)";$/m.exec(themes)?.[1];
      expect(family, `${id}: the scoped family must be a declaration`).toBeDefined();

      const selection = /export const selection = \[([^\]]*)\]/.exec(themes)?.[1] ?? "";
      expect(selection, `${id}: the scoped family ${family} must be selectable`).toContain(
        `"${family}"`,
      );
    }
  });

  it("has every port render the scope with the module's identifier", () => {
    // The component imports the declaration rather than repeating the value, so
    // changing the demo's family is one edit and one typecheck.
    for (const id of Object.keys(ADAPTERS) as (keyof typeof ADAPTERS)[]) {
      const page = fileAt(
        ADAPTERS[id].integrate(scaffoldContext()).files,
        SHOWCASE[id].page,
      )!.contents;

      expect(page, `${id} must import the scoped family`).toContain(
        'import { scopedFamily, selection } from "../themes/themes"',
      );
      expect(page, `${id} must bind the scope to it`).toMatch(
        /<ThemeScope (:family="scopedFamily"|family=\{scopedFamily\})>/,
      );
      // No port may name a family of its own: the value is always the import.
      for (const literal of ["cocoa", "mint", "citrus", "berry", "themvora"]) {
        expect(page, `${id} must not bind the scope to ${literal}`).not.toContain(`family=${literal}`);
        expect(page, `${id} must not bind the scope to "${literal}"`).not.toContain(
          `family="${literal}"`,
        );
      }
    }
  });
});

describe("the showcase links to the documentation's real routes", () => {
  // The links are the only way out of a generated project, and a dead one is a
  // silent 404: the app still builds, still typechecks, still looks fine. The
  // slugs are therefore checked against the documentation app that owns them,
  // and the fixed routes against its router.
  const DOCS_APP = fileURLToPath(new URL("../../../apps/docs/app/", import.meta.url));
  const FRAMEWORK_SLUGS = fileURLToPath(
    new URL("../../../apps/docs/lib/frameworks.tsx", import.meta.url),
  );

  /** Every slug the documentation app publishes a `framework-guides/<slug>` route for. */
  const publishedSlugs = () =>
    [...readFileSync(FRAMEWORK_SLUGS, "utf8").matchAll(/^\s*slug: "([a-z]+)",$/gm)].map((m) => m[1]);

  /**
   * The routes the documentation app really serves, derived from the app itself.
   *
   * This is deliberately *not* derived from `docsLinks()`: the point of the test
   * is to catch a link that names a route which does not exist, and an
   * expectation taken from the implementation under test cannot do that — a
   * typo like `/custom-theme` for `/custom-themes` would be its own truth.
   */
  const realRoutes = () => {
    const routes = [`${DOCS_BASE}/get-started`, `${DOCS_BASE}/custom-themes`, `${DOCS_BASE}/playground`];
    for (const slug of publishedSlugs()) routes.push(`${DOCS_BASE}/framework-guides/${slug}`);
    return new Set(routes);
  };

  it("derives each framework's guide from the docs app's own slug list", () => {
    const published = publishedSlugs();
    expect(published.length, "the docs app should publish several guides").toBeGreaterThan(4);

    for (const id of Object.keys(ADAPTERS) as (keyof typeof ADAPTERS)[]) {
      // The framework id and its guide slug are the same, and the docs app must
      // really have that route — otherwise the hero links to a 404.
      const links = docsLinks(id);
      const guide = links.find((link) => link.href.includes("/framework-guides/"));
      expect(guide, `${id} must link a guide`).toBeDefined();
      expect(guide!.href).toBe(`${DOCS_BASE}/framework-guides/${id}`);
      expect(published, `${id} has no framework-guides route`).toContain(id);
    }
  });

  it("links only routes the documentation app serves", () => {
    // The three fixed routes exist as real app routes, not as guesses.
    for (const route of ["get-started", "custom-themes", "playground"]) {
      expect(
        existsSync(join(DOCS_APP, route, "page.tsx")),
        `the docs app has no /${route} route`,
      ).toBe(true);
    }

    const real = realRoutes();
    for (const id of Object.keys(ADAPTERS) as (keyof typeof ADAPTERS)[]) {
      for (const link of docsLinks(id)) {
        expect(link.href.startsWith(`${DOCS_BASE}/`), `${link.href} must be under the docs origin`).toBe(
          true,
        );
        expect(real, `${link.href} is not a route the docs app serves`).toContain(link.href);
        // No duplicated slash in the path, which is how a concatenation typo
        // shows up — `https://` is the scheme, so only the path is checked.
        expect(link.href.slice(DOCS_BASE.length + 1), `${link.href} has a doubled slash`).not.toContain(
          "//",
        );
      }
    }
  });

  it("renders those hrefs, and no others, in the generated footer", () => {
    // Home, plus the docs routes the app serves and no more.
    const allowed = new Set([`${DOCS_BASE}/`, ...realRoutes()]);

    for (const id of Object.keys(ADAPTERS) as (keyof typeof ADAPTERS)[]) {
      const page = fileAt(
        ADAPTERS[id].integrate(scaffoldContext()).files,
        SHOWCASE[id].page,
      )!.contents;

      // The links live in the footer's link list as object literals
      // (`{ href: "…" }`) and the hero's home link is a JSX attribute
      // (`href="…"`) — both shapes name a URL.
      const rendered = [...page.matchAll(/href[=:]\s*"(https:\/\/[^"]+)"/g)].map((m) => m[1]);

      expect(rendered.length, `${id} must render the documentation links`).toBeGreaterThan(3);
      for (const href of rendered) {
        expect(allowed, `${id}: ${href} is not a route the docs app serves`).toContain(href);
      }
      // The reader's own framework is the guide that gets linked.
      expect(rendered).toContain(`${DOCS_BASE}/framework-guides/${id}`);
    }
  });
});
