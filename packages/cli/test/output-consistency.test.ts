/**
 * Output-consistency tests (§23.3).
 *
 * These are cross-cutting invariants rather than per-command behaviour, so they
 * are asserted across *every* command that claims to support them, driven from
 * the command contract itself. A command added later is covered automatically.
 */
import { join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import { COMMAND_SPECS } from "../src/command-schema.js";
import { colorEnabled } from "../src/output.js";
import { cli, tempDir, type TempDir } from "./helpers.js";

let dir: TempDir | null = null;

afterEach(() => {
  dir?.cleanup();
  dir = null;
  delete process.env["NO_COLOR"];
  delete process.env["FORCE_COLOR"];
});

/** The ANSI escape introducer, which must never reach a JSON payload. */
const ESC = String.fromCharCode(27);

/**
 * A theme fixture, and an integrated project for the commands that need one.
 *
 * The project is created by running `init`, so `add` has a registry that really
 * was generated by the CLI rather than a hand-written approximation.
 */
async function fixtures(): Promise<{ themeFile: string; projectPath: string }> {
  dir = tempDir();
  const themeFile = dir.write("theme.json", JSON.stringify({ name: "x", tokens: {} }));
  dir.write(
    "package.json",
    JSON.stringify({ name: "p", dependencies: { react: "^19.0.0" } }),
  );
  dir.write("vite.config.ts", "export default { plugins: [] };\n");

  const init = await cli("init", dir.path, "--framework", "react", "--preset", "mint", "--no-install");
  expect(init.code, init.output).toBe(0);

  return { themeFile, projectPath: dir.path };
}

/**
 * One invocation per command that declares JSON support.
 *
 * Driven from the schema, so a command that gains `json: true` without being
 * added here fails the coverage assertion below.
 */
function jsonInvocations(context: Awaited<ReturnType<typeof fixtures>>): Record<string, string[]> {
  return {
    list: ["list", "presets", "--json"],
    validate: ["validate", context.themeFile, "--json"],
    inspect: ["inspect", context.themeFile, "--json"],
    diff: ["diff", "mint", "iris", "--json"],
    explain: ["explain", "--preset", "mint", "--json"],
    audit: ["audit", "presets", "--json"],
    doctor: ["doctor", context.projectPath, "--json"],
    init: ["init", "my-app", "--framework", "react", "--plan", "--json"],
    add: ["add", "preset", "mint", "--dir", context.projectPath, "--plan", "--json"],
    migrate: ["migrate", context.themeFile, "--dry-run", "--json"],
  };
}

describe("JSON output", () => {
  it("covers every command the contract marks as JSON-capable", async () => {
    const context = await fixtures();
    const covered = Object.keys(jsonInvocations(context)).sort();
    const declared = COMMAND_SPECS.filter((spec) => spec.json)
      .map((spec) => spec.name)
      .sort();

    // `export` writes CSS or JSON to a file rather than reporting, so it is
    // deliberately not in the set — it is asserted separately below.
    expect(covered).toEqual(declared.filter((name) => name !== "export"));
  });

  it("is valid JSON with no terminal escape sequences", async () => {
    const context = await fixtures();

    for (const [name, argv] of Object.entries(jsonInvocations(context))) {
      const result = await cli(...argv);

      expect(result.stdout, `${name} produced no stdout`).not.toBe("");
      expect(result.stdout, `${name} emitted an escape sequence`).not.toContain(ESC);

      // Throws when stdout is not valid JSON, which is the assertion.
      expect(() => JSON.parse(result.stdout), `${name} stdout is not JSON`).not.toThrow();
    }
  });

  it("keeps stdout parseable even when the command also reports progress", async () => {
    const context = await fixtures();
    // `migrate --json` writes a note, and `init` reports progress. Both must go
    // to stderr so stdout stays a payload.
    const result = await cli("migrate", context.themeFile, "--json");

    expect(() => JSON.parse(result.stdout)).not.toThrow();
    expect(result.stderr.length).toBeGreaterThan(0);
  });
});

describe("colour", () => {
  it("is off by default when stdout is not a terminal", () => {
    // Vitest captures stdout through a mock, so `isTTY` is undefined here —
    // which is exactly the CI case.
    expect(colorEnabled()).toBe(false);
  });

  it("honours NO_COLOR over everything else", () => {
    process.env["FORCE_COLOR"] = "1";
    process.env["NO_COLOR"] = "1";
    expect(colorEnabled()).toBe(false);
  });

  it("produces no escape sequences in human output when colour is off", async () => {
    const context = await fixtures();

    for (const argv of [
      ["list", "presets"],
      ["generate", "--preset", "mint"],
      ["diff", "mint", "iris"],
      ["explain", "--preset", "mint"],
      ["audit", "presets"],
      ["doctor", context.projectPath],
      ["init", "my-app", "--framework", "react", "--plan"],
      ["migrate", context.themeFile, "--dry-run"],
      ["completion", "bash"],
    ]) {
      const result = await cli(...argv);
      expect(result.stdout, `${argv[0]} emitted an escape sequence`).not.toContain(ESC);
      expect(result.stderr, `${argv[0]} emitted an escape sequence`).not.toContain(ESC);
    }
  });

  it("still produces colour when explicitly forced", async () => {
    process.env["FORCE_COLOR"] = "1";
    const result = await cli("list", "presets");

    // Proves the escape sequences exist to be suppressed — otherwise the
    // assertion above would pass for the wrong reason.
    expect(result.stdout).toContain(ESC);
  });
});

describe("errors", () => {
  it("are actionable: every failure names what to do", async () => {
    const context = await fixtures();

    const cases: [string[], string][] = [
      [["validate", join(context.projectPath, "missing.json")], "cannot read file"],
      [["generate", "--preset", "nope"], "unknown preset"],
      [["diff", "nope", "iris"], "cannot resolve"],
      [["init", "my-app", "--framework", "ember", "--plan"], "unknown framework"],
      // A directory with no registry at all — the fixture project itself has
      // one, because `fixtures()` runs `init`.
      [
        ["add", "preset", "mint", "--dir", join(context.projectPath, "not-integrated")],
        "no Themvora theme registry",
      ],
      [["completion", "tcsh"], "unknown shell"],
      [["migrate"], "--file <path> is required"],
    ];

    for (const [argv, expected] of cases) {
      const result = await cli(...argv);
      expect(result.code, `${argv[0]} should have failed`).not.toBe(0);
      expect(result.stderr, `${argv[0]} message`).toContain(expected);
    }
  });

  it("suggests a near miss rather than only rejecting it", async () => {
    const result = await cli("list", "presett");
    expect(result.stderr).toContain("did you mean");
  });
});
