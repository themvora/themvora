/**
 * The five brand-inspired preset recipes.
 *
 * ## What "brand" means here
 *
 * A brand recipe is a **starting point**, not a reproduction — and the
 * distinction that makes it honest is between two different things:
 *
 * - **Exact brand colours** — the values the brand publishes in its brand
 *   guidelines or design system.
 * - **"The colours on the website"** — one implementation, which changes without
 *   notice and includes hover states, overlays, alpha values and gradients.
 *
 * Themvora uses the first. Each recipe carries a `BrandSource` recording *where
 * every value came from*, whether it is official, and how the generator treats
 * it. Only `ANCHOR`-classified values are pinned exactly; everything else is
 * generated by semantic-v2 around them.
 *
 * ```
 * published brand palette → identity layer → semantic-v2 → solver → theme
 * ```
 *
 * The brand controls identity. The generator controls implementation. The solver
 * controls readability — and when the solver has to move an anchor, the recipe
 * reports it rather than pretending it did not.
 *
 * ## Provenance
 *
 * All five declare `"approximate"`: the seed and anchors are the brand's published
 * values, but the surrounding system is Themvora's. Themvora is not affiliated
 * with any of them.
 *
 * @packageDocumentation
 */
